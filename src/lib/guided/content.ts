export const finalBrief = `## From 10-K Risks to a Consulting Problem

Your team has reviewed its company's annual report and identified potential business challenges. Use your confirmed project direction to connect the company's disclosures to a focused consulting question and a framework for analysis.

### 1. Identify the relevant risk

Return to **Item 1A (Risk Factors)** of your company's 10-K.

- Identify one specific risk related to your project direction.
- Cite the risk heading and page number.
- Explain in 1–2 sentences how this risk could affect the business.

You may also reference Item 1 (Business) or Item 7 (MD&A) for context.

### 2. Connect the risk to your project direction

In 2–3 sentences, explain:

- **Business impact:** What outcome could be affected? Consider revenue, costs, customer behavior, operations or strategic growth.
- **Strategic relevance:** How could investigating this direction help the company address the risk or pursue an associated opportunity?

A disclosed risk is not necessarily an existing problem. Distinguish what the company reported from what you believe could happen.

### 3. Formulate your consulting question

Develop **one specific, actionable consulting question** that:

- Identifies a clear business objective or strategic decision.
- Focuses on a defined product, customer segment, market or activity.
- Is narrow enough to investigate meaningfully within six weeks.

**Example:** “How could a nonprofit improve donor retention among first-time contributors?” is more focused than “How can a company improve its fundraising?” Your question should guide analysis, not assume a particular solution is correct.

### 4. Construct your issue tree

Using mathematical, process or decision decomposition from the workshop:

- Identify **3–4 primary buckets**.
- Break each bucket into **at least two specific subquestions or business drivers**.
- Keep branches logical, sufficiently comprehensive and relevant to your question.

Your tree identifies the major factors to investigate before making a recommendation.

### 5. Develop two consulting hypotheses

A **consulting hypothesis** is a preliminary, testable explanation or strategic proposition. It helps prioritize what might matter most and what evidence to investigate.

1. **Review your issue tree.** Which drivers or conditions could most influence the outcome?
2. **Make a specific prediction.** What do you suspect is happening, why, or which approach might work?
3. **Make it testable.** What evidence could support or challenge it?

- Weak: “The nonprofit has a donor engagement problem.”
- Strong: “Declining donor retention, rather than smaller donation amounts, is the primary driver of the nonprofit's fundraising decline.”

Develop **two hypotheses**. For each, state your prediction, identify its issue-tree branch and explain why it is plausible. Hypotheses are starting assumptions to test, not established conclusions.

### 6. Identify the evidence you would need

For each hypothesis, identify **at least two specific pieces of evidence** and explain how each would support or challenge it. Name the information needed, not simply a method or source.

For a donor-retention hypothesis, useful evidence includes:

- Number and percentage of previous donors who contributed again this year.
- Average donation amount and donation frequency among returning donors, compared year over year.

**You do not need to collect or analyze this evidence yet; that comes in Week 3.** Consider whether it is accessible through public reports, industry data, competitor research, surveys or interviews. Acknowledge limitations requiring internal company access.

### Final submission

Submit **one group document** containing:

1. Relevant 10-K risk and citation.
2. Risk-to-project connection explaining business impact.
3. One focused consulting question.
4. Issue tree with 3–4 primary buckets and at least two subquestions per bucket.
5. Two testable hypotheses connected to the tree.
6. Evidence plan with at least two pieces of evidence per hypothesis and their relevance.

**The goal:** a structured, researchable consulting problem and a clear understanding of what to investigate next. Your issue tree and hypotheses form the foundation for the remaining weeks of GAP.`;
